#[derive(Debug, Clone, Copy)]
pub struct Coord {
    pub x: f32,
    pub z: f32,
    pub e: f32,
}

pub trait Indicate {
    /// Generator start
    fn initiation(&mut self);
    /// Layer begin
    fn laybegin(&mut self, index: usize, len: usize);
    /// Draw line carry
    fn drawing(&mut self, segment: &Segment2D, i: usize, n: usize) {
        let config = self.config();
        let index = self.index();
        let filament_width = config.filament_width;
        let first_height = config.first_height;
        let layer_height = config.layer_height;
        let line_width = config.line_width;
        let extrusion_mult = config.extrusion_multiplier;
        let coord = self.coord();
        let dx = segment.end.x - coord.x;
        let dz = segment.end.z - coord.z;
        let length = (dx * dx + dz * dz).sqrt();

        if length > Cov::<N6>::epow() {
            // Calculate extrusion amount
            let filament = consts::PI * filament_width * filament_width / 4.0; // 1.75mm filament
            let layheight = if index == 0 {
                first_height
            } else {
                layer_height
            };
            let path_area = line_width * layheight;
            let extrusion = length * path_area / filament * extrusion_mult;

            coord.e += extrusion;

            coord.x = segment.end.x;
            coord.z = segment.end.z;
            self.drawline(segment, i, n);
        }
    }
    /// Draw line implement
    fn drawline(&mut self, segment: &Segment2D, i: usize, n: usize);
    /// Idle ride carry
    fn idleing(&mut self, segment: &Segment2D, i: usize, n: usize) {
        let coord = self.coord();
        coord.x = segment.start.x;
        coord.z = segment.start.z;
        self.idleride(segment, i, n);
    }
    /// Idle ride implement
    fn idleride(&mut self, segment: &Segment2D, i: usize, n: usize);
    /// Extrusion carry
    fn extruing(&mut self) {
        let config = self.config();
        let enable = config.enable_retraction;
        let distance = config.retraction_distance;
        if enable {
            let coord = self.coord();
            coord.e += distance;
            self.extrusion();
        }
    }
    /// Extrusion implement
    fn extrusion(&mut self);
    /// Retraction carry
    fn retracting(&mut self) {
        let config = self.config();
        let enable = config.enable_retraction;
        let distance = config.retraction_distance;
        if enable {
            let coord = self.coord();
            coord.e -= distance;
            self.retraction();
        }
    }
    /// Retraction implement
    fn retraction(&mut self);
    /// Layer finish
    fn layfinish(&mut self);
    /// Completion
    fn completion(&mut self);
    /// Config
    fn config(&self) -> &Config;
    /// Current position
    fn coord(&mut self) -> &mut Coord;
    /// Current layer index
    fn index(&self) -> usize;
}

/// GCode generator indicator
#[derive(Debug)]
pub struct GCodeInd<'a> {
    coord: Coord,
    pub gcode: GCode,
    index: usize,
    config: &'a Config,
}

impl <'a> GCodeInd<'a> {
    /// Create a new [`GCodeInd`]
    pub fn new(config: &'a Config) -> Self {
        Self {
            coord: Coord {
                x: 0.0,
                z: 0.0,
                e: 0.0,
            },
            gcode: GCode::default(),
            index: 0,
            config,
        }
    }
}

impl <'a> Indicate for GCodeInd<'a> {
    /// G-code generator start
    fn initiation(&mut self) {
        // G-code header
        self.gcode.push(Line::from(&Void).label("Generated by ThdMaker Slicer"));
        self.gcode.push(Line::from(&Void).label(format!("Layer height: {}mm", self.config.layer_height)));
        self.gcode.push(Line::from(&Void).label(format!("Line width: {}mm", self.config.line_width)));
        self.gcode.push(Line::from(&Void).label(format!("Infill: {:.0}%", self.config.infill_density * 100.0)));
        self.gcode.push(Line::from(&Void));

        // Start G-code
        self.gcode.push(Line::from(&G21));
        self.gcode.push(Line::from(&G90));
        self.gcode.push(Line::from(&G28::default()));
        self.gcode.push(Line::from(&*M190::default().set_s(self.config.bed_temperature)));
        self.gcode.push(Line::from(&*M104::default().set_s(self.config.nozzle_temperature)));
        self.gcode.push(Line::from(&*G1::default().set_y(2.0).set_f(3000.0)).label("Move to safe height"));
        self.gcode.push(Line::from(&*G92::default().set_e(0.0)).label("Reset extruder"));
        self.gcode.push(Line::from(&Void));
    }

    /// Layer begin, move to layer height
    fn laybegin(&mut self, index: usize, _: usize) {
        self.index = index;
        self.gcode.push(Line::from(&Void).label(format!("Layer {}\n", self.index + 1)));
        self.gcode.push(Line::from(&*G1::default().set_z(self.config.height(self.index)).set_f(self.config.travel_speed)));
    }

    /// Draw a line segment
    fn drawline(&mut self, segment: &Segment2D, _i: usize, _n: usize) {
        // Print segment - map Point2D (x, z) to printer (X, Y)
        let speed = if self.index == 0 {
            self.config.first_speed
        } else {
            self.config.print_speed
        };
        self.gcode.push(Line::from(&*G1::default().set_x(segment.end.x).set_y(segment.end.z).set_e(self.coord.e).set_f(speed)));
    }

    /// Idle travel move
    fn idleride(&mut self, segment: &Segment2D, _i: usize, _n: usize) {
        self.gcode.push(Line::from(&*G0::default().set_x(segment.start.x).set_y(segment.start.z).set_f(self.config.travel_speed)));
    }

    /// Extrusion
    fn extrusion(&mut self) {
        self.gcode.push(Line::from(&*G1::default().set_e(self.coord.e).set_f(self.config.retraction_speed)));
    }

    /// Retraction
    fn retraction(&mut self) {
        self.gcode.push(Line::from(&*G1::default().set_e(self.coord.e).set_f(self.config.retraction_speed)));
    }

    /// Layer finish, retract and move to next layer height
    fn layfinish(&mut self) {
        self.gcode.push(Line::from(&Void));
    }

    /// Completion, move to safe height and home
    fn completion(&mut self) {
        // End G-code
        self.gcode.push(Line::from(&Void).label("End of print"));
        self.gcode.push(Line::from(&*G1::default().set_y(10.0).set_f(3000.0)).label("Move to safe height"));
        self.gcode.push(Line::from(&*G28::default().set_x(0.0).set_y(0.0)));
        self.gcode.push(Line::from(&*M104::default().set_s(0.0)));
        self.gcode.push(Line::from(&*M140::default().set_s(0.0)));
        self.gcode.push(Line::from(&M84));
    }

    /// Current position
    fn coord(&mut self) -> &mut Coord {
        &mut self.coord
    }

    /// Config
    fn config(&self) -> &Config {
        self.config
    }

    /// Current layer index
    fn index(&self) -> usize {
        self.index
    }
}

/// Strip line draw indicator
pub struct StripInd<'a> {
    coord: Coord,
    index: usize,
    height: f32,
    pub positions: Vec<[f32; 3]>,
    pub colors: Vec<Vec4>,
    solid: Vec4,
    empty: Vec4,
    config: &'a Config,
}

impl <'a> StripInd<'a> {
    /// Create a new [`StripInd`]
    pub fn new(config: &'a Config) -> Self {
        Self {
            coord: Coord {
                x: 0.0,
                z: 0.0,
                e: 0.0,
            },
            index: 0,
            height: 0.0,
            positions: Vec::new(),
            colors: Vec::new(),
            // Colors for different line types
            solid: Color::srgb(0.0, 1.0, 0.0).to_srgba().to_vec4(),
            empty: Color::srgb(0.4, 0.5, 0.6).to_srgba().to_vec4(),

            config,
        }
    }
}

impl <'a> Indicate for StripInd<'a> {
    /// Strip start
    fn initiation(&mut self) {
        self.positions.push([0.0, 0.0, 0.0]);
        self.colors.push(self.solid);
    }

    /// Layer begin, move to layer height
    fn laybegin(&mut self, index: usize, _: usize) {
        self.index = index;
        self.height = self.config.height(self.index);
    }
    
    /// Draw a line segment
    fn drawline(&mut self, segment: &Segment2D, _i: usize, _n: usize) {
        if let Some(last) = self.colors.last() {
            let lpos = self.positions[self.positions.len() - 1];
            if *last != self.solid {
                self.positions.push(lpos);
                self.colors.push(self.solid);
            } else {
                if segment.start.x != lpos[0] || segment.start.z != lpos[2] {
                    self.positions.push(lpos);
                    self.colors.push(self.empty);
                    self.positions.push([segment.start.x, self.height, segment.start.z]);
                    self.colors.push(self.empty);
                }
            }
            self.positions.push([segment.start.x, self.height, segment.start.z]);
            self.colors.push(self.solid);
        }
        self.positions.push([segment.end.x, self.height, segment.end.z]);
        self.colors.push(self.solid);
    }

    /// Idle travel move
    fn idleride(&mut self, segment: &Segment2D, _i: usize, _n: usize) {
        if let Some(last) = self.colors.last() {
            if *last != self.empty {
                self.positions.push(self.positions[self.positions.len() - 1]);
                self.colors.push(self.empty);
            }
            self.positions.push([segment.start.x, self.height, segment.start.z]);
            self.colors.push(self.empty);
        }
        self.positions.push([segment.end.x, self.height, segment.end.z]);
        self.colors.push(self.empty);
    }

    /// Extrusion
    fn extrusion(&mut self) {
    }

    /// Retraction
    fn retraction(&mut self) {
    }

    /// Layer finish, retract and move to next layer height
    fn layfinish(&mut self) {
    }

    /// Completion, move to safe height and home
    fn completion(&mut self) {
    }

    /// Current position
    fn coord(&mut self) -> &mut Coord {
        &mut self.coord
    }

    /// Config
    fn config(&self) -> &Config {
        self.config
    }

    /// Current layer index
    fn index(&self) -> usize {
        self.index
    }
}
